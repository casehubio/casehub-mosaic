import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const MANIFEST_PATH = resolve(
  __dirname,
  '../../../.casehub-packages/META-INF/eidos/personality-vocab.json',
);
const OUTPUT_PATH = resolve(__dirname, '../src/types/personality-vocab.ts');

const HEADER = `// AUTO-GENERATED by scripts/generate-personality-vocab.ts — DO NOT EDIT
// Re-generate: yarn workspace @casehubio/mosaic-core run generate:vocab
// Source: .casehub-packages/META-INF/eidos/personality-vocab.json
`;

interface ManifestTerm {
  value: string;
  label: string;
  description: string;
  detailedDescription: string;
  adjective?: string;
  aliases?: string[];
  signalWeights?: Record<string, number>;
  dominant?: string;
  auxiliary?: string;
  defaultProfile?: Record<string, number>;
  impliesSupervision?: boolean;
}

interface ManifestAxis {
  key: string;
  displayName: string;
  description: string;
  lowPole: string;
  highPole: string;
  lowPoleDescription: string;
  highPoleDescription: string;
}

interface ManifestTendency {
  name: string;
  description: string;
  conditions: Array<{ axis: string; direction: string; threshold: number }>;
}

interface ManifestFrameworkDesc {
  description: string;
  detailedDescription: string;
}

interface Manifest {
  mbti: ManifestTerm[];
  enneagram: ManifestTerm[];
  disc: ManifestTerm[];
  belbin: ManifestTerm[];
  sdi: ManifestTerm[];
  bigFive: ManifestTerm[];
  dispositionAxes: ManifestAxis[];
  behavioralTendencies: ManifestTendency[];
  frameworkDescriptions: Record<string, ManifestFrameworkDesc>;
  archetypeCompatibility: Record<string, Record<string, string[]>>;
  archetypeAffinities: Record<string, { mbti: string[]; enneagram: string[] }>;
  archetype: {
    families: Array<{ name: string; label: string }>;
    terms: Array<{ value: string; label: string; family: string; description: string }>;
  };
}

function toTitleCase(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
}

function q(s: string): string {
  return JSON.stringify(s);
}

function generate(): string {
  const manifest: Manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf-8'));
  const out: string[] = [HEADER];

  const axisKeys = manifest.dispositionAxes.map(a => a.key);
  out.push(`export type DispositionAxisKey = ${axisKeys.map(k => q(k)).join(' | ')};`);
  out.push('');

  const frameworks = [
    { name: 'Mbti', key: 'mbti', terms: manifest.mbti },
    { name: 'Enneagram', key: 'enneagram', terms: manifest.enneagram },
    { name: 'Disc', key: 'disc', terms: manifest.disc },
    { name: 'Belbin', key: 'belbin', terms: manifest.belbin },
    { name: 'Sdi', key: 'sdi', terms: manifest.sdi },
    { name: 'BigFive', key: 'bigFive', terms: manifest.bigFive },
  ];

  out.push(`export type PersonalityFramework = 'mbti' | 'enneagram' | 'disc' | 'belbin' | 'sdi';`);
  out.push(`export type BigFiveDimension = 'O' | 'C' | 'E' | 'A' | 'N';`);
  out.push(`export type BigFivePole = 'high' | 'low';`);
  out.push('');

  for (const fw of frameworks) {
    const values = fw.terms.map(t => t.value);
    out.push(`export const ${fw.name.toUpperCase()}_TYPES = [${values.map(v => q(v)).join(', ')}] as const;`);
    out.push(`export type ${fw.name}Type = typeof ${fw.name.toUpperCase()}_TYPES[number];`);
    out.push('');
  }

  out.push(`export interface VocabTermMeta {`);
  out.push(`  readonly label: string;`);
  out.push(`  readonly description: string;`);
  out.push(`  readonly detailedDescription: string;`);
  out.push(`  readonly adjective: string;`);
  out.push(`  readonly signalWeights: Partial<Record<DispositionAxisKey, number>>;`);
  out.push(`}`);
  out.push('');

  for (const fw of frameworks) {
    out.push(`export const ${fw.name.toUpperCase()}_META: Record<${fw.name}Type, VocabTermMeta> = {`);
    for (const term of fw.terms) {
      const weights = term.signalWeights ?? {};
      const weightEntries = Object.entries(weights)
        .filter(([, v]) => v !== 0)
        .map(([k, v]) => `${q(k)}: ${v}`)
        .join(', ');
      out.push(`  ${q(term.value)}: {`);
      out.push(`    label: ${q(term.label)},`);
      out.push(`    description: ${q(term.description)},`);
      out.push(`    detailedDescription: ${q(term.detailedDescription)},`);
      out.push(`    adjective: ${q(term.adjective ?? '')},`);
      out.push(`    signalWeights: {${weightEntries}},`);
      out.push(`  },`);
    }
    out.push(`};`);
    out.push('');
  }

  out.push(`export const BIG_FIVE_DIMS: readonly BigFiveDimension[] = ['O', 'C', 'E', 'A', 'N'] as const;`);
  out.push('');

  out.push(`export const BIG_FIVE_LABELS: Record<BigFiveDimension, string> = {`);
  out.push(`  O: 'Openness', C: 'Conscientiousness', E: 'Extraversion', A: 'Agreeableness', N: 'Neuroticism',`);
  out.push(`};`);
  out.push('');

  out.push(`export const FRAMEWORK_LABELS: Record<PersonalityFramework, string> = {`);
  out.push(`  mbti: 'MBTI', enneagram: 'Enneagram', disc: 'DISC', belbin: 'Belbin', sdi: 'SDI',`);
  out.push(`};`);
  out.push('');

  out.push(`export const VOCAB_ALL_VALUES: Record<PersonalityFramework | 'bigFive', readonly string[]> = {`);
  for (const fw of frameworks) {
    out.push(`  ${fw.key}: ${fw.name.toUpperCase()}_TYPES,`);
  }
  out.push(`};`);
  out.push('');

  out.push(`export interface DispositionAxisMeta {`);
  out.push(`  readonly key: DispositionAxisKey;`);
  out.push(`  readonly displayName: string;`);
  out.push(`  readonly description: string;`);
  out.push(`  readonly lowPole: string;`);
  out.push(`  readonly highPole: string;`);
  out.push(`  readonly lowPoleDescription: string;`);
  out.push(`  readonly highPoleDescription: string;`);
  out.push(`}`);
  out.push('');

  out.push(`export const DISPOSITION_AXES: readonly DispositionAxisMeta[] = [`);
  for (const axis of manifest.dispositionAxes) {
    out.push(`  {`);
    out.push(`    key: ${q(axis.key)},`);
    out.push(`    displayName: ${q(axis.displayName)},`);
    out.push(`    description: ${q(axis.description)},`);
    out.push(`    lowPole: ${q(axis.lowPole)},`);
    out.push(`    highPole: ${q(axis.highPole)},`);
    out.push(`    lowPoleDescription: ${q(axis.lowPoleDescription)},`);
    out.push(`    highPoleDescription: ${q(axis.highPoleDescription)},`);
    out.push(`  },`);
  }
  out.push(`];`);
  out.push('');

  out.push(`export interface BehavioralTendencyRule {`);
  out.push(`  readonly name: string;`);
  out.push(`  readonly description: string;`);
  out.push(`  readonly conditions: readonly { readonly axis: DispositionAxisKey; readonly direction: 'high' | 'low'; readonly threshold: number }[];`);
  out.push(`}`);
  out.push('');

  out.push(`export const BEHAVIORAL_TENDENCY_RULES: readonly BehavioralTendencyRule[] = [`);
  for (const t of manifest.behavioralTendencies) {
    const conds = t.conditions.map(c =>
      `{ axis: ${q(c.axis)} as DispositionAxisKey, direction: ${q(c.direction)} as 'high' | 'low', threshold: ${c.threshold} }`
    ).join(', ');
    out.push(`  { name: ${q(t.name)}, description: ${q(t.description)}, conditions: [${conds}] },`);
  }
  out.push(`];`);
  out.push('');

  out.push(`export const FRAMEWORK_DESCRIPTIONS: Record<string, { readonly description: string; readonly detailedDescription: string }> = {`);
  for (const [key, desc] of Object.entries(manifest.frameworkDescriptions)) {
    out.push(`  ${q(key)}: { description: ${q(desc.description)}, detailedDescription: ${q(desc.detailedDescription)} },`);
  }
  out.push(`};`);
  out.push('');

  out.push(`export const ARCHETYPE_COMPATIBILITY: Record<string, Record<string, readonly string[]>> = {`);
  for (const [fwKey, mapping] of Object.entries(manifest.archetypeCompatibility)) {
    out.push(`  ${q(fwKey)}: {`);
    for (const [value, families] of Object.entries(mapping)) {
      const titleFamilies = (families as string[]).map(f => toTitleCase(f));
      out.push(`    ${q(value)}: [${titleFamilies.map(f => q(f)).join(', ')}],`);
    }
    out.push(`  },`);
  }
  out.push(`};`);
  out.push('');

  out.push(`export const ARCHETYPE_AFFINITIES: Record<string, { readonly mbti: readonly string[]; readonly enneagram: readonly string[] }> = {`);
  for (const [subKey, affinities] of Object.entries(manifest.archetypeAffinities)) {
    out.push(`  ${q(subKey)}: { mbti: [${affinities.mbti.map(v => q(v)).join(', ')}], enneagram: [${affinities.enneagram.map(v => q(v)).join(', ')}] },`);
  }
  out.push(`};`);
  out.push('');

  out.push(`export interface ArchetypeTerm {`);
  out.push(`  readonly value: string;`);
  out.push(`  readonly label: string;`);
  out.push(`  readonly family: string;`);
  out.push(`  readonly description: string;`);
  out.push(`}`);
  out.push('');
  out.push(`export const ARCHETYPE_TERMS: readonly ArchetypeTerm[] = [`);
  for (const term of manifest.archetype.terms) {
    out.push(`  { value: ${q(term.value)}, label: ${q(term.label)}, family: ${q(toTitleCase(term.family))}, description: ${q(term.description)} },`);
  }
  out.push(`];`);
  out.push('');

  return out.join('\n') + '\n';
}

writeFileSync(OUTPUT_PATH, generate(), 'utf-8');
console.log('Generated personality-vocab.ts');
